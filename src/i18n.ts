const dictionaries: Record<Language, Record<string, string>> = { en, es, fr, hi };

export function translateUI(language: Language): void {
  const strings = dictionaries[language];
  document.documentElement.lang = language;
  document.querySelectorAll<HTMLElement>("[data-i18n]").forEach(element => {
    const key = element.dataset.i18n;
    if (key) element.textContent = strings[key] ?? en[key] ?? element.textContent;
  });
}
